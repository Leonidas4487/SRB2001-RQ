local function HyperFormA()
	if not (leveltime % HyperflashDelay) then

		if Hypercolorpos1 < #Hypercolors1 then
			Hypercolorpos1 = $ + 1
		else
			Hypercolorpos1 = 1
		end
		if Hypercolors1 and Hypercolorpos1 and Hypercolors1[Hypercolorpos1] then
			HyperflashColor1.ramp = Hypercolors1[Hypercolorpos1]
		end

		if Hypercolorpos2 <= #Hypercolors2 then
			Hypercolorpos2 = $ + 1
		else
			Hypercolorpos2 = 1
		end
		if Hypercolors2 and Hypercolorpos2 and Hypercolors2[Hypercolorpos2] then
			HyperflashColor2.ramp = Hypercolors2[Hypercolorpos2]
		end
	end
end

